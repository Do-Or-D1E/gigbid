"""The adapter interface behind the Marketplace MCP server. GigSim and live Upwork both
implement it, so the server's tools (and the graph above them) never know which one
is in use. Switched by `marketplace.mode` in agent/config.yaml."""
from __future__ import annotations

from typing import Any, Protocol


class MarketplaceUnavailable(RuntimeError):
    """The marketplace could not be reached after bounded retries (degraded mode)."""


class MarketplaceRejected(RuntimeError):
    """The marketplace refused the request (policy violation, no Connects, conflict)."""

    def __init__(self, status: int, body: dict) -> None:
        super().__init__(f"{status}: {body}")
        self.status = status
        self.body = body


class MarketplaceAdapter(Protocol):
    name: str

    async def search_jobs(self, query: str, category: str | None, skills: list[str] | None,
                          limit: int) -> list[dict[str, Any]]: ...
    async def get_job(self, job_id: str) -> dict[str, Any]: ...
    async def get_client_history(self, client_id: str) -> dict[str, Any]: ...
    async def get_connects_balance(self) -> dict[str, Any]: ...
    async def quote_connects(self, job_id: str) -> dict[str, Any]: ...
    async def get_pricing_stats(self, category: str | None, skills: list[str] | None) -> dict[str, Any]: ...
    async def get_policy(self) -> dict[str, Any]: ...
    async def list_threads(self) -> list[dict[str, Any]]: ...
    async def list_messages(self, thread_id: str) -> list[dict[str, Any]]: ...
    async def list_proposals(self, status: str | None) -> list[dict[str, Any]]: ...
    async def get_events(self, since: str | None) -> dict[str, Any]: ...
    async def create_proposal_draft(self, payload: dict[str, Any], idempotency_key: str) -> dict[str, Any]: ...
    async def submit_proposal(self, draft_id: str, idempotency_key: str) -> dict[str, Any]: ...
    async def send_message(self, thread_id: str, text: str, idempotency_key: str) -> dict[str, Any]: ...
